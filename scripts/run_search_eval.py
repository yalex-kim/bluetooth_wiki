#!/usr/bin/env python3
"""Run the eval dataset through one or more search strategies and save
per-strategy results JSON (results_wiki.json-compatible shape + telemetry).

Usage:
    python scripts/run_search_eval.py --strategies v0 v1 v2 --limit 5
    python scripts/run_search_eval.py --strategies v2 --questions Q001 Q023
    python scripts/run_search_eval.py --strategies v0 v1 v2            # full 42-question run

Cost warning: a full run is len(strategies) × 42 agent.ask() calls plus the
same number of judge calls (and extra Haiku sufficiency calls under v2).
Smoke-test with --limit 5 first.

Outputs: eval/results_search_<strategy>.json
Shared runner/judge logic lives in eval/runner.py and eval/judge.py.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from eval.runner import load_questions, run_strategy  # noqa: E402


async def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--strategies", nargs="+", default=["v0", "v1", "v2"], choices=("v0", "v1", "v2"))
    ap.add_argument("--questions", nargs="+", default=None, help="specific question ids (e.g. Q001 Q023)")
    ap.add_argument("--limit", type=int, default=None, help="first N questions only")
    ap.add_argument("--concurrency", type=int, default=3)
    args = ap.parse_args()

    try:
        dataset, questions = load_questions(args.questions, args.limit)
    except ValueError as exc:
        raise SystemExit(str(exc))
    if not questions:
        raise SystemExit("No questions selected")
    print(f"Running {len(questions)} question(s) × {len(args.strategies)} strateg(ies)")

    outputs = []
    for strategy in args.strategies:  # strategies sequential; questions concurrent within
        print(f"\n=== strategy {strategy}: {len(questions)} question(s) ===")
        out = await run_strategy(
            strategy,
            questions,
            dataset,
            args.concurrency,
            note=f"search strategy {strategy}; generated by scripts/run_search_eval.py",
        )
        results = json.loads(out.read_text(encoding="utf-8"))
        m, t = results["meta"], results["telemetry"]
        print(f"  → {m['overall_pct']}% ({m['total_weighted']}/{m['total_max_weighted']}), "
              f"avg latency {t['avg_latency_sec']}s, total cost ${t['total_cost_usd']}")
        print(f"  saved {out.relative_to(REPO)}")
        outputs.append(out)

    print("\nDone. Generate the comparison report with:")
    print(f"  python scripts/generate_search_report.py --inputs {' '.join(str(o.relative_to(REPO)) for o in outputs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
